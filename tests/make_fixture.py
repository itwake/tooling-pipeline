def manifest_bytes(attrs: dict) -> bytes:
    lines = ["Manifest-Version: 1.0"] + ["%s: %s" % (k, v) for k, v in attrs.items()]
    return ("\r\n".join(lines) + "\r\n\r\n").encode("utf-8")


def fake_class(name: str, seed: str = "") -> bytes:
    h = hashlib.sha256((name + seed).encode()).digest()
    return b"\xca\xfe\xba\xbe\x00\x00\x00\x41" + h * 8


def sha1_of(path: Path) -> str:
    return hashlib.sha1(Path(path).read_bytes()).hexdigest()


def make_jar(path: Path, entries: dict, manifest=None, stored_members=None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        if manifest is not None:
            zf.writestr("META-INF/MANIFEST.MF", manifest_bytes(manifest))
        for name, data in entries.items():
            zf.writestr(name, data)
        for name, src in (stored_members or {}).items():
            zf.write(src, name, compress_type=zipfile.ZIP_STORED)
    return path


def pom_xml(g: str, a: str, v: str, deps=None) -> bytes:
    dep_xml = "".join(
        "<dependency><groupId>%s</groupId><artifactId>%s</artifactId>%s</dependency>" % (
            dg, da, ("<scope>%s</scope>" % scope) if scope else "")
        for dg, da, scope in (deps or []))
    return ('<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion>'
            "<groupId>%s</groupId><artifactId>%s</artifactId><version>%s</version>"
            "<dependencies>%s</dependencies></project>" % (g, a, v, dep_xml)).encode()


def dep_jar(libdir: Path, g: str, a: str, v: str, classes, extra=None, manifest_extra=None, legal=True,
            classifier=None, no_pom=False, deps=None) -> Path:
    entries = {}
    if not no_pom:
        entries["META-INF/maven/%s/%s/pom.properties" % (g, a)] = (
            "#Generated by Maven\ngroupId=%s\nartifactId=%s\nversion=%s\n" % (g, a, v)).encode()
        entries["META-INF/maven/%s/%s/pom.xml" % (g, a)] = pom_xml(g, a, v, deps)
    if legal:
        entries["META-INF/LICENSE.txt"] = ("Apache License 2.0 for %s" % a).encode()
        entries["META-INF/NOTICE.txt"] = ("%s\nCopyright example" % a).encode()
    for c in classes:
        entries[c] = fake_class(c, a + v)
    entries.update(extra or {})
    man = {"Implementation-Title": a, "Implementation-Version": v, "Automatic-Module-Name": a.replace("-", ".")}
    man.update(manifest_extra or {})
    name = "%s-%s%s.jar" % (a, v, ("-" + classifier) if classifier else "")
    return make_jar(libdir / name, entries, man)


