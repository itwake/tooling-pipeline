#!/usr/bin/env python3
"""Stage 4: generate the Maven project that builds the bundle with maven-shade-plugin.

The generated project
  * declares the selected dependencies at the exact versions found in the application,
  * merges only those artifacts (artifactSet includes), keeps package names (no relocation),
    never minimizes,
  * drops signatures, module-info, INDEX.LIST and relocates LICENSE/NOTICE files to
    META-INF/third-party/<artifact>-<version>/ so they cannot overwrite each other,
  * merges SPI files and Spring metadata with the matching transformers,
  * publishes a dependency-reduced POM that keeps the non-embedded transitive dependencies
    (finalize_bundle_pom.py later restricts those to what the application contained).
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path
from xml.sax.saxutils import escape

sys.path.insert(0, str(Path(__file__).resolve().parent))
from identify import SYNTHETIC_GROUP  # noqa: E402
from bundlelib import (  # noqa: E402
    AppArtifact,
    BUNDLE_BOOT_ATTR,
    BUNDLE_CONTENTS_ATTR,
    BUNDLE_SOURCE_ATTR,
    THIRD_PARTY_DIR,
    classify_entry,
    fail,
    ga_str,
    gav_str,
    log,
    read_json,
    utc_now_iso,
    write_json,
)

POM_TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by mvn-rebundle. Do not edit by hand: regenerate from the source artifact.
  Source: @@SOURCE_DESC@@
-->
<project xmlns="http://maven.apache.org/POM/4.0.0"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>

  <groupId>@@GROUP_ID@@</groupId>
  <artifactId>@@ARTIFACT_ID@@</artifactId>
  <version>@@VERSION@@</version>
  <packaging>jar</packaging>

  <name>@@ARTIFACT_ID@@</name>
  <description>Dependency bundle (@@CONTENTS@@) generated from @@SOURCE_DESC@@</description>

  <properties>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
    <project.build.outputTimestamp>@@TIMESTAMP@@</project.build.outputTimestamp>
  </properties>

  <dependencies>
@@DEPENDENCIES@@
  </dependencies>

  <build>
    <plugins>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-shade-plugin</artifactId>
        <version>@@SHADE_VERSION@@</version>
@@SHADE_PLUGIN_DEPENDENCIES@@
        <executions>
          <execution>
            <id>bundle</id>
            <phase>package</phase>
            <goals>
              <goal>shade</goal>
            </goals>
            <configuration>
              <!-- the merged jar replaces the main artifact: install/deploy publish it directly -->
              <shadedArtifactAttached>false</shadedArtifactAttached>
              <createDependencyReducedPom>true</createDependencyReducedPom>
              <dependencyReducedPomLocation>${project.build.directory}/dependency-reduced-pom.xml</dependencyReducedPomLocation>
              <promoteTransitiveDependencies>true</promoteTransitiveDependencies>
              <minimizeJar>false</minimizeJar>
              <createSourcesJar>@@SOURCES_JAR@@</createSourcesJar>
              <shadeSourcesContent>false</shadeSourcesContent>

              <artifactSet>
                <includes>
@@INCLUDES@@
                </includes>
              </artifactSet>

              <filters>
                <filter>
                  <artifact>*:*</artifact>
                  <excludes>
                    <!-- signatures of the original jars are void after merging -->
                    <exclude>META-INF/*.SF</exclude>
                    <exclude>META-INF/*.RSA</exclude>
                    <exclude>META-INF/*.DSA</exclude>
                    <exclude>META-INF/*.EC</exclude>
                    <exclude>META-INF/SIG-*</exclude>
                    <!-- stale jar index and module descriptors -->
                    <exclude>META-INF/INDEX.LIST</exclude>
                    <exclude>module-info.class</exclude>
                    <exclude>META-INF/versions/*/module-info.class</exclude>
                    <!-- legal files are copied to META-INF/third-party/<artifact>-<version>/ instead -->
                    <exclude>META-INF/LICENSE</exclude>
                    <exclude>META-INF/LICENSE.*</exclude>
                    <exclude>META-INF/LICENSE-*</exclude>
                    <exclude>META-INF/NOTICE</exclude>
                    <exclude>META-INF/NOTICE.*</exclude>
                    <exclude>META-INF/NOTICE-*</exclude>
                    <exclude>META-INF/DEPENDENCIES</exclude>
                    <exclude>META-INF/DEPENDENCIES.*</exclude>
                  </excludes>
                </filter>
              </filters>

              <transformers>
                <transformer implementation="org.apache.maven.plugins.shade.resource.ServicesResourceTransformer"/>
@@APPEND_TRANSFORMERS@@@@PROPS_TRANSFORMERS@@
                <transformer implementation="org.apache.maven.plugins.shade.resource.ManifestResourceTransformer">
                  <manifestEntries>
@@MULTI_RELEASE@@
                    <@@CONTENTS_ATTR@@>@@CONTENTS@@</@@CONTENTS_ATTR@@>
                    <@@SOURCE_ATTR@@>@@SOURCE_ATTR_VALUE@@</@@SOURCE_ATTR@@>
@@BOOT_ATTR_LINE@@
                  </manifestEntries>
                </transformer>
              </transformers>
            </configuration>
          </execution>
        </executions>
      </plugin>
    </plugins>
  </build>
@@DISTRIBUTION_MANAGEMENT@@
</project>
"""

APPEND_TRANSFORMER = """                <transformer implementation="org.apache.maven.plugins.shade.resource.AppendingTransformer">
                  <resource>%s</resource>
                </transformer>
"""
PROPS_TRANSFORMER = """                <transformer implementation="org.springframework.boot.maven.PropertiesMergingResourceTransformer">
                  <resource>%s</resource>
                </transformer>
"""
SHADE_PLUGIN_DEPS = """        <dependencies>
          <!-- provides PropertiesMergingResourceTransformer; version follows the application's Spring Boot -->
          <dependency>
            <groupId>org.springframework.boot</groupId>
            <artifactId>spring-boot-maven-plugin</artifactId>
            <version>%s</version>
          </dependency>
        </dependencies>
"""
DIST_MGMT = """
  <distributionManagement>
%s%s  </distributionManagement>
"""


def dep_xml(gav: dict) -> str:
    lines = [
        "    <dependency>",
        "      <groupId>%s</groupId>" % escape(gav["groupId"]),
        "      <artifactId>%s</artifactId>" % escape(gav["artifactId"]),
        "      <version>%s</version>" % escape(gav["version"]),
    ]
    if gav.get("classifier"):
        lines.append("      <classifier>%s</classifier>" % escape(gav["classifier"]))
    lines.append("    </dependency>")
    return "\n".join(lines)


def component_dir(gav: dict) -> str:
    d = "%s-%s" % (gav["artifactId"], gav["version"])
    if gav.get("classifier"):
        d += "-" + gav["classifier"]
    return d


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--selection", default="out/selection.json")
    ap.add_argument("--source", default=None, help="source metadata JSON (provenance)")
    ap.add_argument("--group-id", required=True)
    ap.add_argument("--artifact-id", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", default="work/bundle", help="generated Maven project directory")
    ap.add_argument("--release-url", default="")
    ap.add_argument("--snapshot-url", default="")
    ap.add_argument("--server-id", default="nexus")
    ap.add_argument("--sources-jar", choices=["true", "false"], default="true")
    ap.add_argument("--timestamp", default="2024-01-01T00:00:00Z", help="project.build.outputTimestamp")
    ap.add_argument("--shade-version", default="3.6.0")
    ap.add_argument("--spring-boot-version", default="", help="override the detected Spring Boot version")
    ap.add_argument("--manifest-out", default="out/bundle-manifest.json")
    ap.add_argument("--inventory", default="", help="inventory.json of the application (default: next to the selection file); "
                    "its coordinates bound what the published POM may promote")
    args = ap.parse_args()

    sel = read_json(args.selection)
    selected = sel.get("selected", [])
    if not selected:
        fail("selection is empty")
    if not sel.get("ok", True):
        fail("selection has errors; refusing to generate")

    # every identified coordinate of the application: the published POM may promote a transitive
    # dependency only when the application had it (finalize_bundle_pom.py)
    inv_path = Path(args.inventory) if args.inventory else Path(args.selection).resolve().parent / "inventory.json"
    app_coordinates = []
    if inv_path.is_file():
        seen = set()
        for d in read_json(inv_path).get("dependencies", []):
            g = d.get("gav")
            if g and g.get("groupId") and g.get("groupId") != SYNTHETIC_GROUP and ga_str(g) not in seen:
                seen.add(ga_str(g))
                app_coordinates.append({"groupId": g["groupId"], "artifactId": g["artifactId"], "version": g.get("version")})
    else:
        log("WARN: inventory not found at %s: the published POM cannot be restricted to the application's dependencies" % inv_path)

    transformers = sel.get("transformers", {})
    boot_version = args.spring_boot_version or sel.get("spring_boot_version")
    if transformers.get("props_merge") and not boot_version:
        fail("properties merging needs a Spring Boot version (--spring-boot-version)")

    source = read_json(args.source) if args.source and Path(args.source).exists() else None
    if source:
        if source["type"] == "image":
            source_desc = "image %s (%s) path %s" % (source["ref"], source.get("digest") or "digest unknown", source.get("app_path"))
            source_attr = "image=%s@%s" % (source["ref"], source.get("digest") or "unknown")
        else:
            ref = source["ref"] if source["ref"].startswith(("http://", "https://")) else Path(source["ref"]).name
            source_desc = "%s %s (sha256 %s)" % (source["type"], ref, source.get("sha256") or "n/a")
            source_attr = "%s=%s@sha256:%s" % (source["type"], Path(source["ref"]).name, source.get("sha256") or "n/a")
    else:
        app_info = sel.get("app", {})
        name = Path(str(app_info.get("local_path"))).name
        source_desc = "%s (sha256 %s)" % (name, app_info.get("sha256") or "n/a")
        source_attr = "app=%s@sha256:%s" % (name, app_info.get("sha256") or "n/a")

    out = Path(args.out).resolve()
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    # keep the selection's order: it is the application's class-loading order, and Shade keeps the
    # first copy of a duplicate entry in dependency order, so duplicates resolve like in the application
    contents = ",".join(gav_str(d["gav"]) for d in selected)
    includes = []
    for d in selected:
        if ga_str(d["gav"]) not in includes:
            includes.append(ga_str(d["gav"]))

    pom = POM_TEMPLATE
    repl = {
        "@@GROUP_ID@@": escape(args.group_id),
        "@@ARTIFACT_ID@@": escape(args.artifact_id),
        "@@VERSION@@": escape(args.version),
        "@@CONTENTS@@": escape(contents),
        "@@SOURCE_DESC@@": escape(source_desc),
        "@@TIMESTAMP@@": escape(args.timestamp),
        "@@DEPENDENCIES@@": "\n".join(dep_xml(d["gav"]) for d in selected),
        "@@SHADE_VERSION@@": escape(args.shade_version),
        "@@SHADE_PLUGIN_DEPENDENCIES@@": (SHADE_PLUGIN_DEPS % escape(boot_version)) if transformers.get("props_merge") else "",
        "@@SOURCES_JAR@@": args.sources_jar,
        "@@INCLUDES@@": "\n".join("                  <include>%s</include>" % escape(ga) for ga in includes),
        "@@APPEND_TRANSFORMERS@@": "".join(APPEND_TRANSFORMER % escape(r) for r in transformers.get("append", [])),
        "@@PROPS_TRANSFORMERS@@": "".join(PROPS_TRANSFORMER % escape(r) for r in transformers.get("props_merge", [])),
        "@@MULTI_RELEASE@@": "                    <Multi-Release>true</Multi-Release>" if transformers.get("multi_release") else "",
        "@@CONTENTS_ATTR@@": BUNDLE_CONTENTS_ATTR,
        "@@SOURCE_ATTR@@": BUNDLE_SOURCE_ATTR,
        "@@SOURCE_ATTR_VALUE@@": escape(source_attr),
        "@@BOOT_ATTR_LINE@@": ("                    <%s>%s</%s>" % (BUNDLE_BOOT_ATTR, escape(boot_version), BUNDLE_BOOT_ATTR)) if boot_version else "",
    }
    dist = ""
    if args.release_url or args.snapshot_url:
        rel = "    <repository>\n      <id>%s</id>\n      <url>%s</url>\n    </repository>\n" % (escape(args.server_id), escape(args.release_url)) if args.release_url else ""
        snap = "    <snapshotRepository>\n      <id>%s</id>\n      <url>%s</url>\n    </snapshotRepository>\n" % (escape(args.server_id), escape(args.snapshot_url)) if args.snapshot_url else ""
        dist = DIST_MGMT % (rel, snap)
    repl["@@DISTRIBUTION_MANAGEMENT@@"] = dist
    for k, v in repl.items():
        pom = pom.replace(k, v)
    (out / "pom.xml").write_text(pom, encoding="utf-8")

    # ---- third-party legal files + contents list ---------------------------------------
    res_root = out / "src" / "main" / "resources" / THIRD_PARTY_DIR.rstrip("/")
    res_root.mkdir(parents=True)
    app = AppArtifact(sel["app"]["local_path"])
    by_path = {j.path_in_app: j for j in app.dependency_jars()}
    components = []
    unidentified = []
    install = []
    components_dir = out / "components"
    components_dir.mkdir(parents=True, exist_ok=True)
    for d in selected:
        dj = by_path.get(d["path_in_app"])
        if dj is None:
            fail("%s disappeared from the application" % d["path_in_app"])
        comp_dir = res_root / component_dir(d["gav"])
        copied = []
        with dj.open() as zf:
            for n in zf.namelist():
                if classify_entry(n) == "legal":
                    target = comp_dir / n[len("META-INF/"):]
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(zf.read(n))
                    copied.append(n)
        synthetic = d.get("gav_source") == "synthetic"
        # every component is installed into the build's local repository from the application's own
        # bytes, so the Shade build never depends on the repository having (the same) artifact
        target = components_dir / d["name"]
        target.write_bytes(dj.data)
        install.append({"name": d["name"], "file": str(target), "gav": d["gav"], "synthetic": synthetic,
                        "sha1": d.get("sha1"), "sha256": d["sha256"]})
        if synthetic:
            unidentified.append({"name": d["name"], "file": str(target), "gav": d["gav"], "hint": d.get("synthetic_hint"),
                                 "sha1": d.get("sha1"), "sha256": d["sha256"]})
        components.append({
            "gav": d["gav"],
            "coordinate": gav_str(d["gav"]),
            "file": d["name"],
            "path_in_app": d["path_in_app"],
            "sha256": d["sha256"],
            "size": d["size"],
            "legal_files": copied,
            "synthetic": synthetic,
            "hint": d.get("synthetic_hint") if synthetic else None,
            "flags": d.get("flags", {}),
        })
    app.close()
    lines = ["# Dependency bundle %s:%s:%s" % (args.group_id, args.artifact_id, args.version),
             "# Source: %s" % source_desc,
             "# coordinate  sha256  original-file"]
    for c in components:
        lines.append("%s  %s  %s" % (c["coordinate"], c["sha256"], c["file"]))
    (res_root / "BUNDLE-CONTENTS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    manifest = {
        "bundle": {"groupId": args.group_id, "artifactId": args.artifact_id, "version": args.version},
        "coordinate": "%s:%s:%s" % (args.group_id, args.artifact_id, args.version),
        "contents_attr": contents,
        "source": source or sel.get("app"),
        "source_desc": source_desc,
        "components": components,
        "install": install,
        "unidentified": unidentified,
        "classpath_source": sel.get("classpath_source"),
        "transformers": transformers,
        "spring_boot_version": boot_version,
        "shade_version": args.shade_version,
        "sources_jar": args.sources_jar == "true",
        "timestamp": args.timestamp,
        "project_dir": str(out),
        "expected_jar": str(out / "target" / ("%s-%s.jar" % (args.artifact_id, args.version))),
        "reduced_pom": str(out / "target" / "dependency-reduced-pom.xml"),
        "pom": str(out / "target" / ("%s-%s.pom" % (args.artifact_id, args.version))),
        "application_coordinates": app_coordinates,
        "generated_at": utc_now_iso(),
    }
    write_json(args.manifest_out, manifest)

    log("Bundle project generated in %s" % out)
    log("  coordinate : %s" % manifest["coordinate"])
    log("  contents   : %s" % contents)
    log("  transformers: services%s%s%s" % (
        ", append(%d)" % len(transformers.get("append", [])) if transformers.get("append") else "",
        ", props-merge(%d) via spring-boot-maven-plugin %s" % (len(transformers["props_merge"]), boot_version) if transformers.get("props_merge") else "",
        ", Multi-Release" if transformers.get("multi_release") else ""))
    if unidentified:
        log("  unidentified: %d jar(s) embedded under synthetic coordinates (%s)" % (
            len(unidentified), ", ".join(u["name"] for u in unidentified)))
    log("  install    : install_components.py --manifest %s   (components from the application's bytes)" % args.manifest_out)
    log("  build      : mvn -f %s -B clean verify" % (out / "pom.xml"))
    log("  finalize   : finalize_bundle_pom.py --manifest %s   (published POM: promoted dependencies limited to the application's %d coordinates)" % (
        args.manifest_out, len(app_coordinates)))


if __name__ == "__main__":
    main()
